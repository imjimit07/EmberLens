class HybridRow(dict):
    """Mapping row that also supports SQLite's positional row indexing."""

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return tuple(dict.values(self))[key]
        return dict.__getitem__(self, key)

    def __iter__(self):
        # sqlite3.Row iterates values, which is relied on by CSV export.
        return iter(dict.values(self))


def hybrid_row_factory(cursor):
    description = cursor.description or ()
    names = [column.name if hasattr(column, "name") else column[0] for column in description]

    def make_row(values: Sequence[Any]) -> HybridRow:
        return HybridRow(zip(names, values))

    return make_row


def adapt_sql(sql: str) -> str:
    """Translate the limited SQLite SQL dialect used by the app to PostgreSQL."""
    statement = sql.strip()
    ignore_insert = bool(re.match(r"INSERT\s+OR\s+IGNORE\s+INTO\b", statement, re.I))
    if ignore_insert:
        statement = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO\b", "INSERT INTO", statement,
                           count=1, flags=re.I)
        if not re.search(r"\bON\s+CONFLICT\b", statement, re.I):
            statement = statement.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    # Application SQL uses positional '?' placeholders and does not contain
    # question marks inside SQL string literals.
    return statement.replace("?", "%s")


class PostgresConnection:
    is_postgres = True

    def __init__(self, database_url: str):
        try:
            import psycopg
        except ImportError as exc:  # pragma: no cover - only reached on cloud config
            raise RuntimeError("Install psycopg[binary] to use Supabase PostgreSQL") from exc

        self._connection = psycopg.connect(
            database_url,
            connect_timeout=10,
            sslmode="require",
            prepare_threshold=None,  # Supabase shared transaction pooler has no prepared statements.
            row_factory=hybrid_row_factory,
        )

    def execute(self, sql: str, params: Sequence[Any] | None = None):
        cursor = self._connection.cursor()
        cursor.execute(adapt_sql(sql), params or ())
        return cursor

    def executemany(self, sql: str, params: Iterable[Sequence[Any]]):
        cursor = self._connection.cursor()
        cursor.executemany(adapt_sql(sql), params)
        return cursor

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        return False


def connect_postgres(database_url: str) -> PostgresConnection:
    return PostgresConnection(database_url)


def initialize_postgres_schema(db: PostgresConnection) -> None:
    """Create the app's tables/indexes idempotently on a fresh Supabase project."""
    for statement in POSTGRES_SCHEMA.split(";"):
        if statement.strip():
            db.execute(statement)
    db.commit()
